package com.musiclibrary.theme;

/**
 * Enumeration representing available UI application themes.
 */
public enum AppTheme {
    /**
     * Dark theme (macOS Dark style).
     */
    DARK,

    /**
     * Light theme (macOS Light style).
     */
    LIGHT,

    /**
     * Follows the host operating system's theme preference (Dark or Light).
     */
    SYSTEM
}
